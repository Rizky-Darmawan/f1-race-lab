"""Load OpenF1 laps and expand each finished lap into live sector events."""

import json
from dataclasses import dataclass, replace
from datetime import datetime, timedelta
from typing import Any, TypeGuard
from urllib.request import urlopen


@dataclass
class Lap:
    """One live snapshot of a lap.

    ``date_start`` is when this snapshot should be published. Sector and lap
    durations stay ``None`` until the car has reached that split.
    """

    date_start: str
    driver_number: int
    duration_sector_1: float | None
    duration_sector_2: float | None
    duration_sector_3: float | None
    i1_speed: int | None
    i2_speed: int | None
    is_pit_out_lap: bool
    lap_duration: float | None
    lap_number: int
    meeting_key: int
    segments_sector_1: list[int] | None
    segments_sector_2: list[int] | None
    segments_sector_3: list[int] | None
    session_key: int
    st_speed: int | None


class _LapExploder:
    """Explode one finished lap into all the sectors timing events.

    Newly generated rows reflect the time in which a particular car starts a sector.
    - Lap start: all the timing converted to None, date start is the data that comes with the API
    - Sector 2 start: generated by date start + s1 duration, will only have sector 1 time filled
    - Sector 3 start: generated by date start + s1 + s2 duration, only s1 and s2 times are filled
    - End of lap: generated by date start + lap duration, all the timings are filled
    """

    def _copy_lap(self, lap: Lap, **overrides: Any) -> Lap:
        return replace(lap, **overrides)

    def _shift_date(self, date_start: str, seconds: float) -> str:
        start = datetime.fromisoformat(date_start)
        shifted = start + timedelta(microseconds=round(seconds * 1_000_000))
        return shifted.isoformat(timespec="microseconds")

    def _is_duration(self, value: Any) -> TypeGuard[int | float]:
        return isinstance(value, (int, float)) and not isinstance(value, bool)

    def _lap_start_event(self, lap: Lap) -> Lap:
        return self._copy_lap(
            lap,
            duration_sector_1=None,
            duration_sector_2=None,
            duration_sector_3=None,
            lap_duration=None,
        )

    def _sector_2_start_event(self, lap: Lap) -> Lap | None:
        sector_1 = lap.duration_sector_1
        if not self._is_duration(sector_1):
            return None
        return self._copy_lap(
            lap,
            date_start=self._shift_date(lap.date_start, sector_1),
            duration_sector_2=None,
            duration_sector_3=None,
            lap_duration=None,
        )

    def _sector_3_start_event(self, lap: Lap) -> Lap | None:
        sector_1 = lap.duration_sector_1
        sector_2 = lap.duration_sector_2
        if not self._is_duration(sector_1) or not self._is_duration(sector_2):
            return None
        return self._copy_lap(
            lap,
            date_start=self._shift_date(lap.date_start, sector_1 + sector_2),
            duration_sector_3=None,
            lap_duration=None,
        )

    def _lap_complete_event(self, lap: Lap) -> Lap | None:
        if not self._is_duration(lap.lap_duration):
            return None
        return self._copy_lap(
            lap,
            date_start=self._shift_date(lap.date_start, lap.lap_duration),
        )

    def explode(self, lap: Lap) -> list[Lap]:
        """Return the lap-start, sector-start, and lap-complete events for one lap."""
        events = [
            self._lap_start_event(lap),
            self._sector_2_start_event(lap),
            self._sector_3_start_event(lap),
            self._lap_complete_event(lap),
        ]
        return [event for event in events if event is not None]


class LapData:
    """Wrapper for the OpenF1 laps endpoint."""

    _BASE_URL = "https://api.openf1.org/v1/laps?session_key={session_key}&driver_number=1"

    def __init__(self, session_key: int) -> None:
        self._session_key = session_key
        self._url = self._BASE_URL.format(session_key=session_key)

    def construct_laps_from_api(self) -> list[Lap]:
        """Fetch finished laps and return a sector event for each timing split."""
        response = urlopen(self._url).read().decode("utf-8")
        datas = json.loads(response)
        results = []
        for data in datas:
            result = Lap(
                date_start=data["date_start"],
                driver_number=data["driver_number"],
                duration_sector_1=data["duration_sector_1"],
                duration_sector_2=data["duration_sector_2"],
                duration_sector_3=data["duration_sector_3"],
                i1_speed=data["i1_speed"],
                i2_speed=data["i2_speed"],
                is_pit_out_lap=data["is_pit_out_lap"],
                lap_duration=data["lap_duration"],
                lap_number=data["lap_number"],
                meeting_key=data["meeting_key"],
                segments_sector_1=data["segments_sector_1"],
                segments_sector_2=data["segments_sector_2"],
                segments_sector_3=data["segments_sector_3"],
                session_key=data["session_key"],
                st_speed=data["st_speed"],
            )
            results.extend(_LapExploder().explode(result))
        return results
